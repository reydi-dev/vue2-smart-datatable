import { test, expect } from '@playwright/test'

test('the complete main demo runs without Vuetify or fonts and supports search, columns and export', async ({
  page,
}) => {
  const fonts: string[] = []
  page.on('request', (request) => {
    if (/\.(woff2?|ttf)(\?|$)/.test(request.url())) fonts.push(request.url())
  })
  await page.goto('/')
  await expect(page.locator('.v-application,.v-btn,.v-input,.mdi')).toHaveCount(0)
  await page.getByRole('searchbox', { name: 'Search by name' }).fill('Person 67')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  const columns = page.getByRole('button', { name: 'Columns', exact: true })
  await columns.click()
  const dialog = page.getByRole('dialog', { name: 'Columns', exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('checkbox', { name: 'Email', exact: true }).uncheck()
  await dialog.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(page.getByRole('columnheader', { name: 'Email', exact: true })).toHaveCount(0)
  await expect(columns).toBeFocused()
  await columns.click()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(columns).toBeFocused()
  const exportButton = page.getByRole('button', { name: 'Export', exact: true })
  await exportButton.click()
  await exportButton.press('Tab')
  await expect(page.getByRole('button', { name: 'CSV — Current page', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(exportButton).toBeFocused()
  await exportButton.click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'CSV — Current page', exact: true }).click()
  expect((await download).suggestedFilename()).toMatch(/\.csv$/)
  await page.getByRole('searchbox', { name: 'Search by name' }).fill('No matching person')
  await expect(page.locator('.sdt-state')).toContainText('No matching items')
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(25)
  expect(fonts).toEqual([])
})

test('native numeric ranges and typed multi-select filters work with keyboard access', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Filters', exact: true }).click()
  await page.getByRole('combobox', { name: 'Age · Condition', exact: true }).selectOption('between')
  await page.getByRole('spinbutton', { name: 'Age · From', exact: true }).fill('20')
  await page.getByRole('spinbutton', { name: 'Age · To', exact: true }).fill('22')
  await expect(page.locator('.sdt-pagination__count')).toHaveText('1–6 of 6')
  await page.getByRole('combobox', { name: 'Active · Condition', exact: true }).selectOption('in')
  await page.getByRole('listbox', { name: 'Active · Value', exact: true }).selectOption('1')
  await expect(page.locator('.sdt-pagination__count')).toHaveText('1–2 of 2')
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page.locator('.sdt-pagination__count')).toHaveText('1–25 of 67')
})

test('Persian mobile dark controls and modal remain usable without page overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('fa')
  await page.getByRole('combobox', { name: 'پوسته', exact: true }).selectOption('dark')
  await expect(page.locator('.sdt-root')).toHaveAttribute('dir', 'rtl')
  await page.getByRole('button', { name: 'ستون‌ها', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'ستون‌ها', exact: true })
  await expect(dialog).toHaveCSS('background-color', 'rgb(32, 43, 38)')
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'اعمال', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'بستن', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'ستون‌ها', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'فیلترها', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Name · شرط', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('checkbox', { name: 'غیرفعال', exact: true }).check()
  await expect(page.getByRole('button', { name: 'فیلترها', exact: true })).toBeDisabled()
})
